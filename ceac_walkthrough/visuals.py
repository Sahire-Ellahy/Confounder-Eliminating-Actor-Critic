def rollout_route(kind, label, benchmark="weak_signal_m4", mode=0, seed=7):
    """An illustrative route generated by the actual environment, not a training curve."""
    env = environment(kind, (mode, mode, mode), benchmark=benchmark)
    observation, _ = env.reset(seed=seed, options={"episode_index": 0})
    cells, total, events = [], 0., []
    for _ in range(env.config.max_steps):
        state = env.decode(observation)
        cells.append((state.column if kind == "deepsea" else state.col, state.row))
        if kind == "deepsea":
            action = deepsea.TV if label == "sonar-sweep" else deepsea.policy_action(label, state, env.config)
        else:
            action = frozenlake.policy_action(label, state)
        observation, reward, terminated, truncated, info = env.step(action)
        total += reward
        events.append(info["diagnostic_event"])
        if terminated or truncated:
            state = env.decode(observation)
            cells.append((state.column if kind == "deepsea" else state.col, state.row))
            return dict(cells=np.asarray(cells), total_return=total,
                        terminal_success=info["terminal_success"], events=events)
    raise AssertionError("Route exceeded its declared horizon")


def draw_undertow():
    style()
    fig, ax = plt.subplots(figsize=(11, 8))
    ax.set_facecolor("#eaf5ff")
    for row in range(9):
        for col in range(row+1):
            ax.add_patch(Rectangle((col-.46, row-.46), .92, .92,
                                  facecolor="white", edgecolor="#cfdfeb", lw=.7))
    for label, color, caption in (("exploit", BLUE, "Coherent rightward route"),
                                  ("sonar-sweep", MAGENTA, "Sonar sweep / undertow")):
        route = rollout_route("deepsea", label)
        xy = route["cells"]
        ax.plot(xy[:,0], xy[:,1], color=color, lw=4, marker="o", ms=6, label=caption)
    ax.scatter([0], [0], s=150, color=GREEN, zorder=7)
    ax.scatter([8], [8], marker="*", s=420, color=GREEN, edgecolor="white", zorder=7)
    ax.scatter([2], [2], marker="D", s=160, color=ORANGE, edgecolor="white", zorder=7)
    box = dict(boxstyle="round,pad=.6", fc="white", ec="#cad6e0")
    ax.annotate("PROBE AT THE GATE\nSignal probability: 0.15 vs 0.85\nUses the spare step; preserves progress",
                xy=(2,2), xytext=(4.1,1.4), fontsize=12, bbox=box,
                arrowprops=dict(arrowstyle="->", color=GREEN, lw=2))
    ax.annotate("BUSY, BUT OFF COURSE\nNuisance consumes depth without\nrightward progress. Goal is missed.",
                xy=(0,6), xytext=(1.4,5.3), fontsize=12, color=MAGENTA, bbox=box,
                arrowprops=dict(arrowstyle="->", color=MAGENTA, lw=2))
    ax.text(7.7, 7.25, "GOAL", color=GREEN, weight="bold", fontsize=15)
    ax.text(.3, -.15, "START", color=GREEN, weight="bold")
    ax.set(xlim=(-.7,9.1), ylim=(8.8,-.8), xticks=range(9), yticks=range(9),
           xlabel="Rightward progress", ylabel="Depth used (finite-horizon budget)")
    ax.set_aspect("equal")
    ax.set_title("Undertow DeepSea: novelty can consume the route budget", pad=18, weight="bold")
    ax.legend(loc="upper left", bbox_to_anchor=(0,-.13), ncol=2, frameon=False)
    fig.text(.5,.01,"Actual reset/step paths. A challenge follows the rightward route but changes its reward law.",
             ha="center", fontsize=11, color="#444444")
    fig.tight_layout(rect=(0,.06,1,1))
    return fig


